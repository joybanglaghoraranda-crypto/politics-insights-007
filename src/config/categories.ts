export function getCategoryBySlug(slug: string): CategoryDefinition | undefined {
  return CATEGORIES.find((cat) => cat.slug.toLowerCase() === slug.toLowerCase());
}

export function getCategoryByName(name: string): CategoryDefinition | undefined {
  const normalized = name.trim().toLowerCase();
  return CATEGORIES.find(
    (cat) =>
      cat.nameEn.toLowerCase() === normalized ||
      cat.nameBn === name.trim() ||
      cat.slug.toLowerCase() === normalized
  );
}

export function getCategorySlug(categoryName: string): string {
  const found = getCategoryByName(categoryName);
  return found ? found.slug : 'latest-news';
}
